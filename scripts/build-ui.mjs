import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from '@vue/compiler-dom';
import { build } from 'esbuild';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const app = path.join(root, 'ui/modules/apps/TaxiDriverHUD');
const template = await fs.readFile(path.join(app, 'hud-template.html'), 'utf8');
const { code } = compile(template, {mode: 'module', prefixIdentifiers: true,
  hoistStatic: true, cacheHandlers: true, isCustomElement: tag => tag === 'taxi-driver-hud'});
await fs.writeFile(path.join(app, 'hud-render.js'), '// Generated by pnpm build:ui; edit hud-template.html.\n' + code + '\n');
await build({entryPoints: [path.join(app, 'external/entry.js')], outfile: path.join(app, 'external/hud.bundle.js'),
  // BeamNG Repo reviewers must be able to inspect the shipped code directly.
  // Keep production Vue optimizations, readable formatting and function names.
  bundle: true, minify: false, format: 'iife', globalName: 'TaxiDriverVue', target: ['es2020'],
  alias: {vue: 'vue/dist/vue.runtime.esm-bundler.js'},
  define: {'process.env.NODE_ENV': '"production"', __VUE_OPTIONS_API__: 'false',
    __VUE_PROD_DEVTOOLS__: 'false', __VUE_PROD_HYDRATION_MISMATCH_DETAILS__: 'false'},
  legalComments: 'linked'});
console.log('Compiled Vue template and Connected Phone runtime.');
